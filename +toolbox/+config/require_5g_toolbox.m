function require_5g_toolbox()
%REQUIRE5GTOOLBOX Check that required 5G Toolbox functions are available.

required_functions = { ...
    'nrCarrierConfig', ...
    'nrPDSCHConfig', ...
    'nrCRCEncode', ...
    'nrDLSCH', ...
    'nrDLSCHDecoder', ...
    'nrDLSCHInfo', ...
    'nrLDPCEncode', ...
    'nrLDPCDecode', ...
    'nrRateMatchLDPC', ...
    'nrRateRecoverLDPC', ...
    'nrSymbolModulate', ...
    'nrSymbolDemodulate', ...
    'nrTDLChannel', ...
    'nrCDLChannel', ...
    'nrEqualizeMMSE'};

for idx = 1:numel(required_functions)
    if exist(required_functions{idx}, 'file') ~= 2
        error("toolbox:Missing5GToolbox", ...
            "Required function %s was not found. Install 5G Toolbox.", ...
            required_functions{idx});
    end
end
end
