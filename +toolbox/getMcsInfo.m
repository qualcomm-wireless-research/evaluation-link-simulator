function mcs_info = getMcsInfo(mcs_index, mcs_table_name)
%GETMCSINFO Return a fixed-MCS entry for single-codeword PDSCH.

if nargin < 2 || strlength(string(mcs_table_name)) == 0
    mcs_table_name = "qam64";
end

[mcs_table, normalized_table_name] = getMcsTable(mcs_table_name);
row_idx = find(mcs_table(:, 1) == mcs_index, 1);
if isempty(row_idx)
    error("toolbox:UnknownMCS", ...
        "Unsupported MCS index %d for table %s.", mcs_index, normalized_table_name);
end

bits_per_symbol = mcs_table(row_idx, 2);
target_code_rate_x1024 = mcs_table(row_idx, 3);
spectral_efficiency = bits_per_symbol * (target_code_rate_x1024 / 1024);
ps_mb_nu = NaN;

if size(mcs_table, 2) >= 4
    spectral_efficiency = mcs_table(row_idx, 2);
    bits_per_symbol = mcs_table(row_idx, 3);
    target_code_rate_x1024 = mcs_table(row_idx, 4);
end

if size(mcs_table, 2) >= 5
    ps_mb_nu = mcs_table(row_idx, 5);
end

if target_code_rate_x1024 <= 0
    error("toolbox:ReservedMCS", ...
        "MCS index %d is reserved in table %s.", mcs_index, normalized_table_name);
end

target_code_rate = target_code_rate_x1024 / 1024;

mcs_info = struct();
mcs_info.index = mcs_index;
mcs_info.table = normalized_table_name;
mcs_info.bitsPerSymbol = bits_per_symbol;
mcs_info.modulation = bitsPerSymbolToModulation(bits_per_symbol);
mcs_info.targetCodeRate = target_code_rate;
mcs_info.spectralEfficiency = spectral_efficiency;
mcs_info.nu_MB = ps_mb_nu;
end

