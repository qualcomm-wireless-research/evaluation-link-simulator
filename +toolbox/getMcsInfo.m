function modulation = bitsPerSymbolToModulation(bits_per_symbol)
switch bits_per_symbol
    case 2
        modulation = 'QPSK';
    case 4
        modulation = '16QAM';
    case 6
        modulation = '64QAM';
    case 8
        modulation = '256QAM';
    case 10
        modulation = '1024QAM';
    otherwise
        error("toolbox:UnsupportedModulation", ...
            "Unsupported bits per symbol value %g.", bits_per_symbol);
end
end
